export function getTile(index: number): TileDefinition {
  const normalized = ((index % 40) + 40) % 40;
  return BOARD_TILES[normalized]!;
}

export function formatTileLabel(tile: TileDefinition): string {
  return tile.deedNumber !== undefined ? `#${tile.deedNumber} ${tile.name}` : tile.name;
}
